@torch.no_grad()
def denoising_check(model, x0: torch.Tensor, condition: torch.Tensor) -> tuple[float, float]:
    """Same computation as validation_step, without self.log. Should be close to the logged val_loss."""
    b = x0.shape[0]
    t = torch.randint(0, model.timesteps, (b,), device=model.device)
    noise = torch.randn_like(x0)

    x_t = model.q_sample(x0, t, noise)
    noise_pred = model.model(x_t, condition, t)
    loss = F.mse_loss(model._crop(noise_pred), model._crop(noise))

    x0_hat = model._rev_qsample(x_t, t, noise_pred)
    recon_loss = F.mse_loss(model._crop(x0_hat), model._crop(x0))
    return loss.item(), recon_loss.item()


def ensemble_metrics(prediction: torch.Tensor, truth: torch.Tensor, target_vars: list[str]) -> dict:
    """prediction: (B, E, C, H, W), truth: (B, C, H, W)."""
    ens_mean = prediction.mean(dim=1)
    err = ens_mean - truth
    rmse = torch.nanmean(err ** 2, dim=(0, 2, 3)).sqrt()
    bias = torch.nanmean(err, dim=(0, 2, 3))
    if prediction.shape[1] > 1:
        spread = prediction.var(dim=1, unbiased=True).mean(dim=(0, 2, 3)).sqrt()
    else:
        spread = torch.full_like(rmse, float("nan"))

    metrics = {}
    for i, var in enumerate(target_vars):
        metrics[var] = {
            "rmse": rmse[i].item(),
            "bias": bias[i].item(),
            "spread": spread[i].item(),
            "spread_skill": (spread[i] / rmse[i]).item(),
        }
    return metrics


def print_metrics(metrics: dict, label: str):
    print(f"\n{label}")
    print(f"{'var':<10}{'rmse':>12}{'bias':>12}{'spread':>12}{'spread/rmse':>14}")
    for var, m in metrics.items():
        print(f"{var:<10}{m['rmse']:>12.4f}{m['bias']:>12.4f}{m['spread']:>12.4f}{m['spread_skill']:>14.3f}")


def load_stats(config_path: str, stats_path: str | None):
    if stats_path is None:
        full_config = toml.load(config_path)
        stats_path = full_config.get("preprocessing", {}).get("normalization_stats_path")
    if stats_path is None or not Path(stats_path).exists():
        print("No normalization stats found; results stay in normalized space.")
        return None
    return xr.open_dataset(stats_path)


def unnormalize(t: torch.Tensor, stats: xr.Dataset, target_vars: list[str]) -> torch.Tensor:
    """Works on any tensor whose channel axis is dim -3."""
    t = t.clone()
    for i, var in enumerate(target_vars):
        if var not in stats.data_vars:
            print(f"Warning: '{var}' not in stats file, left normalized.")
            continue
        mean = float(stats[var].sel(statistic="targ_mean").values)
        std = float(stats[var].sel(statistic="targ_std").values)
        t[..., i, :, :] = t[..., i, :, :] * std + mean
    return t


def plot_sample(prediction: torch.Tensor, truth: torch.Tensor, target_vars: list[str], path: Path, title: str):
    """Plots batch item 0: truth, ensemble mean, member 0, error, ensemble std."""
    p = prediction[0].numpy()  # (E, C, H, W)
    t = truth[0].numpy()       # (C, H, W)
    n = len(target_vars)
    fig, axes = plt.subplots(n, 5, figsize=(22, 4 * n), squeeze=False)

    for i, var in enumerate(target_vars):
        truth_i = t[i]
        mean_i = p[:, i].mean(axis=0)
        std_i = p[:, i].std(axis=0)
        err_i = mean_i - truth_i
        vmin, vmax = np.nanpercentile(truth_i, [1, 99])
        elim = np.nanpercentile(np.abs(err_i), 99)

        panels = [
            (truth_i, "truth", dict(vmin=vmin, vmax=vmax, cmap="RdYlBu_r")),
            (mean_i, "ensemble mean", dict(vmin=vmin, vmax=vmax, cmap="RdYlBu_r")),
            (p[0, i], "member 0", dict(vmin=vmin, vmax=vmax, cmap="RdYlBu_r")),
            (err_i, "mean - truth", dict(vmin=-elim, vmax=elim, cmap="RdBu_r")),
            (std_i, "ensemble std", dict(cmap="magma")),
        ]
        for ax, (field, name, kw) in zip(axes[i], panels):
            im = ax.imshow(field, origin="lower", **kw)
            ax.set_title(f"{var}: {name}")
            ax.set_xticks([])
            ax.set_yticks([])
            fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


