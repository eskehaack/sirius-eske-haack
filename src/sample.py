def load_checkpoint(run_id: str, checkpoint: str = "last") -> tuple[pl.LightningModule, dict]:
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    checkpoint_path = Path(f"./checkpoints/{run_id}/{checkpoint}.ckpt")
    log_path = Path(f"./logs/{run_id}/version_0/hparams.yaml")
    if log_path.exists():
        with open(log_path, "r") as f:
            hparams = yaml.safe_load(f)
        m_spec = hparams.get("hyperparameters", {}).get("diffusion_model", "conditional_ddpm")
    else:
        m_spec = "conditional_ddpm"

    print(f"Loading model {m_spec} from checkpoint: {checkpoint_path}")
    if not checkpoint_path.exists():
        raise FileNotFoundError(
            f"Checkpoint file not found: {checkpoint_path}\nModel training did not complete as expected."
        )

    model = MODELREGISTRY[m_spec].load_from_checkpoint(checkpoint_path)
    model.eval()
    model.to(device)
    # _load_batch caches the interpolated static field; reset so it is rebuilt from this run's data
    model.static = None
    return model, hparams


