def main(
    run_id: str,
    checkpoint: str = "last",
    config_path: str = "./src/configs/training_config.toml",
    split: str = "val",
    batch_index: int = 0,
    num_batches: int = 1,
    batch_size: int = 1,
    num_workers: int | None = None,
    ensemble_size: int = 5,
    timesteps: int = 500,
    sample_type: str = "ddpm",
    cfg_scale: float = 1.0,
    eta: float = 0.0,
    seed: int = 42,
    amp: bool = False,
    stats_path: str | None = None,
    s_churn: float = 0.0
):
    pl.seed_everything(seed, workers=True)
    torch.set_float32_matmul_precision("medium")
    os.makedirs("dist_test", exist_ok=True)  # sample_ddpm writes step diagnostics here

    model, config = load_checkpoint(run_id, checkpoint)
    device = model.device
    hyperparams = config["hyperparameters"]

    train_cfg = parse_config("training", config_path)
    if num_workers is None:
        num_workers = int(train_cfg["num_workers"])

    datamodule, loader = build_dataloader(config_path, split, batch_size, num_workers)
    stats = load_stats(config_path, stats_path)

    # Training ran with precision="16-mixed"; --amp reproduces that for the forward passes
    use_amp = amp and device.type == "cuda"
    autocast = (
        torch.autocast(device_type="cuda", dtype=torch.float16)
        if use_amp else contextlib.nullcontext()
    )

    out_root = Path(f"./samples/{run_id}/datamodule_{split}")
    sample_hparams = {
        "cfg_scale": cfg_scale, "eta": eta, 
        "sample_type": sample_type, "save_metrics": False,
        "S_churn": s_churn, "S_min": 500, "S_noise": 5.0
    }
    
    dataset = datamodule.val_ds if split == "val" else datamodule.train_ds

    batches = itertools.islice(loader, batch_index, batch_index + num_batches)
    for batch_idx, batch in enumerate(batches, start=batch_index):
        batch = move_batch_like_trainer(batch, model, datamodule, device)
        x, y, static, idx = batch
        target_vars = list(y.keys())  # same order _load_batch stacks them in
        date = dataset.predictors.isel(time=dataset.indices[idx]).time.values

        with torch.no_grad(), autocast:
            x0, condition = model._load_batch(batch)
            x0 = x0.to(device)
            condition = condition.to(device)

            if torch.isnan(condition).any():
                print("Warning: condition contains NaNs (training feeds it unchanged as well).")

            if hyperparams["diffusion_model"] in ["conditional_ddpm", "custom_cold", "cold_diffusion"]:
                noise_loss, recon_loss = denoising_check(model, x0, condition)
                print(f"\n[batch {batch_idx}] denoising check: noise_mse={noise_loss:.4f}, x0_recon_mse={recon_loss:.4f}")
            else:
                noise_loss, recon_loss = float("nan"), float("nan")
                print(f"\n[batch {batch_idx}] denoising check skipped for model {hyperparams['diffusion_model']}")

            members = [
                model.sample(
                    condition,
                    num_steps=timesteps,
                    hparams=sample_hparams,
                )
                for _ in range(ensemble_size)
            ]

        # (B, E, C, H, W), cropped exactly like the training loss
        prediction = model._crop(torch.stack(members, dim=1)).float().cpu()
        truth = model._crop(x0).float().cpu()

        out_dir = out_root / f"batch{batch_idx:05d}"
        out_dir.mkdir(parents=True, exist_ok=True)
        tag = f"{sample_type}_{ensemble_size}_{timesteps}_cfg{cfg_scale:g}"

        metrics = {"normalized": ensemble_metrics(prediction, truth, target_vars)}
        print_metrics(metrics["normalized"], "Normalized space")
        np.save(out_dir / f"prediction_norm_{tag}.npy", prediction.numpy())
        np.save(out_dir / f"truth_norm.npy", truth.numpy())
        plot_sample(prediction, truth, target_vars, out_dir / f"diagnostics_norm_{tag}.png",
                    title=f"{run_id} | {split} batch {batch_idx} | normalized | {date}")

        if stats is not None:
            prediction_phys = unnormalize(prediction, stats, target_vars)
            truth_phys = unnormalize(truth, stats, target_vars)
            metrics["physical"] = ensemble_metrics(prediction_phys, truth_phys, target_vars)
            print_metrics(metrics["physical"], "Physical units (still residuals if targets are residuals)")
            np.save(out_dir / f"prediction_phys_{tag}.npy", prediction_phys.numpy())
            np.save(out_dir / f"truth_phys.npy", truth_phys.numpy())
            plot_sample(prediction_phys, truth_phys, target_vars, out_dir / f"diagnostics_phys_{tag}.png",
                        title=f"{run_id} | {split} batch {batch_idx} | physical | {date}")

        with open(out_dir / f"metrics_{tag}.yaml", "w") as f:
            yaml.safe_dump(
                {"noise_mse": noise_loss, "x0_recon_mse": recon_loss, "target_vars": target_vars, **metrics},
                f,
            )


def parse_args():
    parser = argparse.ArgumentParser(description="Sample from a DDPM model using the training DataModule.")

    parser.add_argument("--run_id", type=str, required=True, help="Run ID defining directory for checkpoint file")
    parser.add_argument("--checkpoint", type=str, default="last", help="Name of checkpoint file")
    parser.add_argument("--config_path", type=str, default="./src/configs/training_config.toml",
                        help="Training config used to build the DataModule")
    parser.add_argument("--split", type=str, default="val", choices=["train", "val"],
                        help="Which dataloader to draw batches from")
    parser.add_argument("--batch_index", type=int, default=0, help="Index of the first batch to sample")
    parser.add_argument("--num_batches", type=int, default=1, help="How many consecutive batches to sample")
    parser.add_argument("--batch_size", type=int, default=1,
                        help="Batch size for the DataModule (each item gets its own ensemble)")
    parser.add_argument("--num_workers", type=int, default=None,
                        help="Dataloader workers (defaults to the training config value)")
    parser.add_argument("--ensemble_size", type=int, default=5, help="Ensemble members per batch item")
    parser.add_argument("--timesteps", type=int, default=1000, help="Number of reverse diffusion steps")
    parser.add_argument("--sample_type", type=str, default="ddpm", choices=["ddpm", "ddim"],
                        help="Type of sampling to use")
    parser.add_argument("--cfg_scale", type=float, default=1.0,
                        help="Classifier-free guidance scale for DDPM (1.0 = no guidance)")
    parser.add_argument("--eta", type=float, default=0.0, help="DDIM stochasticity (0 = deterministic)")
    parser.add_argument("--seed", type=int, default=42, help="Seed passed to pl.seed_everything")
    parser.add_argument("--amp", action="store_true",
                        help="Run forward passes in fp16 autocast, like precision='16-mixed' in training")
    parser.add_argument("--stats_path", type=str, default=None,
                        help="Normalization stats file; defaults to [preprocessing].normalization_stats_path in the config")
    parser.add_argument("--s_churn", type=float, default=0.0, help="DDPM stochasticity for EDM sampler")

    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    main(**vars(args))