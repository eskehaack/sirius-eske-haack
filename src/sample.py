def build_dataloader(config_path: str, split: str, batch_size: int, num_workers: int):
    datamodule = DataModule(
        batch_size=batch_size,
        num_workers=num_workers,
        config_path=config_path,
    )
    # trainer.fit() calls setup("fit"), which builds both train and val datasets
    stage = "test" if split == "test" else "fit"
    datamodule.prepare_data()
    datamodule.setup(stage=stage)

    loaders = {
        "train": datamodule.train_dataloader,
        "val": datamodule.val_dataloader,
    }
    return datamodule, loaders[split]()


def move_batch_like_trainer(batch, model: pl.LightningModule, datamodule: pl.LightningDataModule, device):
    """Run the same before/transfer/after batch hooks Lightning runs during training."""
    batch = datamodule.on_before_batch_transfer(batch, 0)
    batch = model.on_before_batch_transfer(batch, 0)
    batch = model.transfer_batch_to_device(batch, device, 0)
    batch = datamodule.on_after_batch_transfer(batch, 0)
    batch = model.on_after_batch_transfer(batch, 0)
    return batch


