class LitEDM(pl.LightningModule):
    def __init__(
        self,
        target_channels: int = 1,
        condition_channels: int = 1,
        base_channels: int = 128,
        channel_mults: Sequence[int] = (1, 2, 4, 8),
        timesteps: int = 1000,
        beta_start: float = 1e-4,
        beta_end: float = 2e-2,
        schedule: str = "linear",
        dropout: float = 0.0,
        lr: float = 2e-4,
        image_size: int = 432,
        attention: bool = False,
    ):
        super().__init__()
        self.save_hyperparameters()

        cfg = TrainConfig(
            experiment_name = "edm.v0",
            sigma_data = 1.0,
            p_mean = -0.4,
            p_std = 1.0,
            sigma_min = 0.002,
            sigma_max = 160.0,
            rho = 7.0,
        )

        self.model = EDMModel.from_config(
            cfg=cfg
        )

        self.image_size = image_size
        self.lr = lr

        self.initial_target_shape = (412, 424)
        self.pad_x = (self.image_size - self.initial_target_shape[0]) // 2
        self.pad_y = (self.image_size - self.initial_target_shape[1]) // 2
        self.pad_tuple = (self.pad_y, self.pad_y, self.pad_x, self.pad_x)

        self.static = None  # Allocation

    def _crop(self, x: torch.Tensor) -> torch.Tensor:
        """
        Generated by Claude Opus 5.5. Prompt summary: user asked why a conditional DDPM
        trains well but samples with high error; this helper fixes swapped crop axes.
        pad_x pads H (dim 2) and pad_y pads W (dim 3), matching self.pad_tuple.
        """
        H, W = x.shape[-2], x.shape[-1]
        return x[..., self.pad_x : H - self.pad_x, self.pad_y : W - self.pad_y]

    def _load_batch(self, batch):
        x, y, static, _ = batch

        x0 = torch.stack(
            list(y.values()),
            dim=1,
        )

        x0 = F.pad(
            x0,
            pad=self.pad_tuple,
            mode="constant",
            value=0.0,
        )

        # Interpolate the condition to match the target shape
        condition = F.interpolate(
            x,
            size=self.initial_target_shape,
            mode="bilinear",
            align_corners=False,
        )
        # Then pad to meet model requirements
        condition = F.pad(
            condition,
            pad=self.pad_tuple,
            mode="constant",
            value=0.0,
        )

        # Only interpolate static once and store it for future use
        if self.static is None:
            # Collapse the batch dimension to allow for broadcasting with other batch sizes
            static = static[0] # Get rid of batch dimension
            static = static.unsqueeze(0)  # Add batch dimension back

            static = F.interpolate(
                static,
                size=self.initial_target_shape,
                mode="bilinear",
                align_corners=False,
            )
            self.static = F.pad(
                static,
                pad=self.pad_tuple,
                mode="constant",
                value=0.0,
            )

        static = self.static.expand(condition.size(0), -1, -1, -1)  # Expand to match batch size
        condition = torch.cat([condition, static], dim=1)

        return x0, condition

    def _batch_loss(self, batch) -> torch.Tensor:
        residual, cond = batch
        return self.model.training_loss(residual, cond)

    @log_time
    def training_step(self, batch, batch_idx):
        x0, condition = self._load_batch(batch)
        loss = self._batch_loss((x0, condition))

        self.log("train_loss", loss, prog_bar=True, on_step=True, on_epoch=True)
        return loss

    def validation_step(self, batch, batch_idx):
        x0, condition = self._load_batch(batch)
        loss = self._batch_loss((x0, condition))

        self.log("val_loss", loss, prog_bar=True, on_epoch=True)
        return loss

    def sample(self, condition: torch.Tensor, num_steps: int = 1, **kwargs) -> torch.Tensor:
        """
        Sample from the model given a condition.
        """
        self.model.eval()
        with torch.no_grad():
            samples = self.model.sample(cond=condition, n_steps=num_steps, device=self.device)
        return samples

    def configure_optimizers(self):
        # Optimizer and scheduler
        optimizer = torch.optim.AdamW(self.parameters(), lr=self.hparams.lr)
        scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
            optimizer, T_max=self.hparams.max_epochs, eta_min=self.hparams.lr * 0.01
        )
        return [optimizer], [{"scheduler": scheduler, "interval": "step"}]