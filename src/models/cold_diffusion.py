from __future__ import annotations

import math

import torch
import torch.nn.functional as F

from src.callbacks.timer import log_time

from src.models.base_diffusion import LitConditionalDiffusion

class LitColdDiffusion(LitConditionalDiffusion):
    """
    Cold Diffusion model for climate downscaling, following:
        Bansal et al. "Cold Diffusion: Inverting Arbitrary Image Transforms
        Without Noise." arXiv:2208.09392 (2022).

    Degradation (in residual space):
        r0     = x0_HR - x_LR          (target residual)
        D(r0, t) = alpha_bar_t * r0    (interpolate residual toward zero)

    This means:
        x_t = x_LR + alpha_bar_t * r0
            = (1 - alpha_bar_t) * x_LR + alpha_bar_t * x0_HR

    i.e. at t=0 you have pure HR, at t=T you have pure LR.

    The network R is trained to predict r0 (the full residual) from the
    degraded input x_t and the conditioning x_LR. Sampling starts from
    x_T = x_LR (r_T = 0) and runs Algorithm 2:

        r_hat   = R(x_s, condition, s)
        x_{s-1} = x_s + (alpha_bar_{s-1} - alpha_bar_s) * r_hat

    which walks x_s along the interpolation path back to x0_HR.
    """

    def __init__(
        self,
        backbone: str = "cond_unet",
        hyperparameters: dict = {},
    ) -> None:
        super().__init__(backbone, hyperparameters)

        schedule = hyperparameters.get("schedule", "linear")
        timesteps = hyperparameters.get("timesteps", 1000)
        beta_start = hyperparameters.get("beta_start", 1e-4)
        beta_end = hyperparameters.get("beta_end", 2e-2)

        alpha_bars = self._make_alpha_bars(schedule, timesteps, beta_start, beta_end)

        self.register_buffer("alpha_bars", alpha_bars)   # [T]  ᾱ_t, descending 1→0

    # ------------------------------------------------------------------
    # Schedule
    # ------------------------------------------------------------------

    def _make_alpha_bars(
        self,
        schedule: str,
        timesteps: int,
        beta_start: float,
        beta_end: float,
    ) -> torch.Tensor:
        """
        Return alpha_bars (ᾱ_t) for t = 0 … T-1.

        For cold diffusion we only need ᾱ_t directly (no per-step betas
        are used in the degradation or the sampler), but we derive them
        from the same schedule machinery as the DDPM classes so that
        schedule hyperparameters are comparable across models.

        ᾱ_0 ≈ 1  (nearly clean HR at the start of the forward process)
        ᾱ_{T-1} ≈ 0  (pure LR at the end)
        """
        if schedule == "linear":
            betas = torch.linspace(beta_start, beta_end, timesteps)
        elif schedule == "cosine":
            s = 0.008
            t = torch.linspace(0, timesteps, timesteps + 1)
            alphas_cumprod = torch.cos(((t / timesteps) + s) / (1 + s) * math.pi * 0.5) ** 2
            alphas_cumprod = alphas_cumprod / alphas_cumprod[0]
            betas = 1 - (alphas_cumprod[1:] / alphas_cumprod[:-1])
            betas = torch.clamp(betas, min=0, max=0.02)
        elif schedule == "exponential":
            betas = torch.logspace(
                torch.log10(torch.tensor(beta_start)),
                torch.log10(torch.tensor(beta_end)),
                timesteps,
            )
        elif schedule == "quadratic":
            t = torch.linspace(0, timesteps - 1, timesteps)
            betas = beta_start + (beta_end - beta_start) * (t / (timesteps - 1)) ** 2
        elif schedule == "sigmoid":
            t = torch.linspace(0, timesteps - 1, timesteps)
            betas = beta_start + (beta_end - beta_start) / (
                1 + torch.exp(-12 * (t / (timesteps - 1) - 0.5))
            )
        else:
            raise ValueError(f"Unknown schedule: {schedule}")

        alphas = 1.0 - betas
        return torch.cumprod(alphas, dim=0)

    # ------------------------------------------------------------------
    # Degradation (forward process)
    # ------------------------------------------------------------------

    def degrade(
        self,
        r0: torch.Tensor,
        t: torch.Tensor,
    ) -> torch.Tensor:
        """
        D(r0, t) = ᾱ_t * r0

        Degrades the residual r0 = (x0_HR - x_LR) toward zero (i.e. toward
        the LR image in pixel space) according to the noise schedule.

        Args:
            r0: [B, C, H, W]  target residual (HR - LR)
            t:  [B]           integer timestep indices

        Returns:
            r_t: [B, C, H, W]  degraded residual at step t
        """
        ab = self.alpha_bars[t][:, None, None, None]
        return ab * r0

    # ------------------------------------------------------------------
    # Training & validation
    # ------------------------------------------------------------------

    @log_time
    def training_step(self, batch, batch_idx):
        r0, condition = self._load_batch(batch)
        x_lr = condition[:, :self.target_channels]

        b = r0.shape[0]
        t = torch.randint(0, self.timesteps, (b,), device=self.device)

        # Forward process: degrade the residual
        r_t = self.degrade(r0, t)

        # x_t in pixel space: used as the noisy input to the UNet
        x_t = x_lr + r_t

        # Network predicts r0 (the full residual) directly
        r0_pred = self.model(x_t, condition, t)

        loss = F.l1_loss(r0_pred, r0)

        self.log("train_loss", loss, prog_bar=True, on_step=True, on_epoch=True)
        return loss

    def validation_step(self, batch, batch_idx):
        r0, condition = self._load_batch(batch)
        x_lr = condition[:, :self.target_channels]

        b = r0.shape[0]
        t = torch.randint(0, self.timesteps, (b,), device=self.device)

        r_t = self.degrade(r0, t)
        x_t = x_lr + r_t

        r0_pred = self.model(x_t, condition, t)

        loss = F.l1_loss(r0_pred, r0)

        self.log("val_loss", loss, prog_bar=True, on_epoch=True)
        return loss

    # ------------------------------------------------------------------
    # Sampling  (Algorithm 2 from Bansal et al. 2022)
    # ------------------------------------------------------------------

    @torch.inference_mode()
    def sample(
        self,
        condition: torch.Tensor,
        num_steps: int = 200,
        hparams: dict = {},
    ) -> torch.Tensor:
        """
        Cold Diffusion sampler (Algorithm 2, Bansal et al. 2022).

        The update rule at each step s -> s-1 is:

            r_hat   = R(x_s, condition, s)
            x_{s-1} = x_s + (ᾱ_{s-1} - ᾱ_s) * r_hat

        which is Algorithm 2 instantiated for D(r0, t) = ᾱ_t * r0:

            x_{s-1} = x_s - D(r_hat, s) + D(r_hat, s-1)
                     = x_s - ᾱ_s * r_hat + ᾱ_{s-1} * r_hat
                     = x_s + (ᾱ_{s-1} - ᾱ_s) * r_hat

        Sampling starts from x_T = x_LR  (r_T = 0, i.e. pure LR).
        The final output is x_0_HR = x_LR + accumulated residual.

        Args:
            condition:  [B, condition_channels, H, W]  full conditioning tensor
                        (upsampled LR channels + static features)
            x_lr:       [B, target_channels, H, W]     upsampled LR image,
                        used as the starting point and residual anchor
            num_steps:  number of reverse steps (can be << training timesteps;
                        100-200 is usually sufficient)
            hparams:    dictionary of additional hyperparameters (currently unused)

        Returns:
            x0_hr: [B, target_channels, H, W]  downscaled HR prediction
        """
        self.eval()

        x_lr = condition[:, :self.target_channels]  # extract LR channels
        device = self.device
        b = condition.shape[0]

        T = self.timesteps

        # Evenly-spaced timestep subsequence T-1 ... 0  (same subsampling as DDIM)
        step_indices = torch.linspace(T - 1, 0, num_steps, device=device).long()

        # alpha_bar at each step and at the preceding (less-degraded) step
        ab_s      = self.alpha_bars[step_indices]          # [num_steps]
        ab_s_prev = torch.cat([
            self.alpha_bars[step_indices[1:]],
            torch.zeros(1, device=device, dtype=self.alpha_bars.dtype),
        ], dim=0)                                          # [num_steps], last entry = 0

        # Start from pure LR (r_T = 0  =>  x_T = x_LR)
        x = x_lr.clone()

        for i, t_idx in enumerate(step_indices):
            t_batch = torch.full((b,), t_idx.item(), device=device, dtype=torch.long)

            # Predict the full residual r0
            r_hat = self.model(x, condition, t_batch)

            # Algorithm 2 step:  x_{s-1} = x_s + (ᾱ_{s-1} - ᾱ_s) * r_hat
            delta_ab = (ab_s_prev[i] - ab_s[i])           # scalar, negative (ᾱ decreasing)
            x = x + delta_ab * r_hat

        return x
