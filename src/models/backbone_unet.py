# UNet blocks
# -------------------------


class ResBlock(nn.Module):
    def __init__(self, in_ch: int, out_ch: int, time_dim: int, dropout: float = 0.0):
        super().__init__()

        self.norm1 = nn.GroupNorm(8, in_ch)
        self.conv1 = nn.Conv2d(in_ch, out_ch, 3, padding=1)

        self.time_proj = nn.Linear(time_dim, out_ch)

        self.norm2 = nn.GroupNorm(8, out_ch)
        self.dropout = nn.Dropout(dropout)
        self.conv2 = nn.Conv2d(out_ch, out_ch, 3, padding=1)

        self.skip = nn.Conv2d(in_ch, out_ch, 1) if in_ch != out_ch else nn.Identity()

    def forward(self, x: torch.Tensor, t_emb: torch.Tensor) -> torch.Tensor:
        h = self.conv1(F.silu(self.norm1(x)))
        h = h + self.time_proj(F.silu(t_emb))[:, :, None, None]
        h = self.conv2(self.dropout(F.silu(self.norm2(h))))
        return h + self.skip(x)


class DownBlock(nn.Module):
    def __init__(self, in_ch: int, out_ch: int, time_dim: int, dropout: float):
        super().__init__()
        self.res1 = ResBlock(in_ch, out_ch, time_dim, dropout)
        self.res2 = ResBlock(out_ch, out_ch, time_dim, dropout)
        self.down = nn.Conv2d(out_ch, out_ch, 4, stride=2, padding=1)

    def forward(self, x, t_emb):
        x = self.res1(x, t_emb)
        x = self.res2(x, t_emb)
        skip = x
        x = self.down(x)
        return x, skip


class UpBlock(nn.Module):
    def __init__(
        self, in_ch: int, skip_ch: int, out_ch: int, time_dim: int, dropout: float
    ):
        super().__init__()
        self.up = nn.ConvTranspose2d(in_ch, out_ch, 4, stride=2, padding=1)
        self.res1 = ResBlock(out_ch + skip_ch, out_ch, time_dim, dropout)
        self.res2 = ResBlock(out_ch, out_ch, time_dim, dropout)

    def forward(self, x, skip, t_emb):
        x = self.up(x)
        x = torch.cat([x, skip], dim=1)
        x = self.res1(x, t_emb)
        x = self.res2(x, t_emb)
        return x



class BottleneckAttention(nn.Module):
    """
    Generated by Claude Sonnet 4.6
    Multi-head self-attention module for UNet bottleneck, following the standard
    DDPM pattern of ResBlock -> Attention -> ResBlock at the lowest spatial resolution.
    """
    def __init__(self, channels: int, num_heads: int = 8):
        super().__init__()
        assert channels % num_heads == 0, "channels must be divisible by num_heads"

        self.norm = nn.GroupNorm(8, channels)
        self.attn = nn.MultiheadAttention(
            embed_dim=channels,
            num_heads=num_heads,
            batch_first=True,
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, C, H, W = x.shape

        # Normalize
        h = self.norm(x)

        # Flatten spatial dims to sequence: [B, H*W, C]
        h = h.view(B, C, H * W).permute(0, 2, 1)

        # Self-attention — query, key, value are all h
        h, _ = self.attn(h, h, h)

        # Reshape back to spatial: [B, C, H, W]
        h = h.permute(0, 2, 1).view(B, C, H, W)

        # Residual connection
        return x + h


class ConditionalUNet(nn.Module):
    """
    Predicts noise epsilon.

    Input:
        noisy target image: [B, target_channels, H, W]
        condition image:    [B, condition_channels, H, W]

    Internally concatenates them along channels:
        [x_t, condition]
    """

    def __init__(
        self,
        target_channels: int = 1,
        condition_channels: int = 1,
        base_channels: int = 64,
        channel_mults: Sequence[int] = (1, 2, 4, 8),
        time_dim: int = 256,
        dropout: float = 0.0,
        attention: bool = False,
    ):
        super().__init__()

        self.target_channels = target_channels
        self.condition_channels = condition_channels
        self.attention = attention

        in_channels = target_channels + condition_channels

        self.time_mlp = nn.Sequential(
            SinusoidalTimeEmbedding(time_dim),
            nn.Linear(time_dim, time_dim * 4),
            nn.SiLU(),
            nn.Linear(time_dim * 4, time_dim),
        )

        chs = [base_channels * m for m in channel_mults]

        self.input_conv = nn.Conv2d(in_channels, chs[0], 3, padding=1)

        self.downs = nn.ModuleList()
        in_ch = chs[0]
        for out_ch in chs:
            self.downs.append(DownBlock(in_ch, out_ch, time_dim, dropout))
            in_ch = out_ch

        self.mid1 = ResBlock(chs[-1], chs[-1], time_dim, dropout)
        if self.attention:
            self.mid_attn = BottleneckAttention(chs[-1], num_heads=8)
        self.mid2 = ResBlock(chs[-1], chs[-1], time_dim, dropout)

        self.ups = nn.ModuleList()
        rev_chs = list(reversed(chs))
        in_ch = rev_chs[0]
        for skip_ch in rev_chs:
            out_ch = skip_ch
            self.ups.append(UpBlock(in_ch, skip_ch, out_ch, time_dim, dropout))
            in_ch = out_ch

        self.out = nn.Sequential(
            nn.GroupNorm(8, chs[0]),
            nn.SiLU(),
            nn.Conv2d(chs[0], target_channels, 3, padding=1),
        )

    def forward(
        self, x_t: torch.Tensor, condition: torch.Tensor, t: torch.Tensor
    ) -> torch.Tensor:
        t_emb = self.time_mlp(t)

        x = torch.cat([x_t, condition], dim=1)
        x = self.input_conv(x)

        skips = []
        for down in self.downs:
            x, skip = down(x, t_emb)
            skips.append(skip)

        x = self.mid1(x, t_emb)
        if self.attention:
            x = self.mid_attn(x)
        x = self.mid2(x, t_emb)

        for up in self.ups:
            skip = skips.pop()
            x = up(x, skip, t_emb)

        return self.out(x)