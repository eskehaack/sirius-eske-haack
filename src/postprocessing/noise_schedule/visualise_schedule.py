import xarray as xr
import matplotlib.pyplot as plt
import numpy as np

from pathlib import Path
import toml


CONFIG_PATH = Path("./src/configs/sample_config.toml")
CONFIG = toml.load(CONFIG_PATH)
VALUE_KEY = "__xarray_dataarray_variable__"

BETA_START = 1e-4
BETA_END = 2e-2
TIMESTEPS = 1000

N_SHOWN = 11   # number of timestep snapshots to display per schedule

SCHEDULES = [
    "linear",
    "cosine",
    "exponential",
]


def noise_schedule(
    schedule: str,
    timesteps: int,
    beta_start: float,
    beta_end: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    if schedule == "linear":
        betas = np.linspace(beta_start, beta_end, timesteps)
    elif schedule == "cosine":
        s = 0.001
        t = np.linspace(0, timesteps, timesteps + 1)
        alphas_cumprod = np.cos(((t / timesteps) + s) / (1 + s) * np.pi * 0.5) ** 2
        alphas_cumprod = alphas_cumprod / alphas_cumprod[0]
        betas = 1 - (alphas_cumprod[1:] / alphas_cumprod[:-1])
        betas = np.clip(betas, a_min=0, a_max=0.999)
    elif schedule == "exponential":
        betas = np.logspace(np.log10(beta_start), np.log10(beta_end), timesteps)
    else:
        raise ValueError(f"Unknown noise schedule: {schedule}")

    alphas = 1.0 - betas
    alpha_bars = np.cumprod(alphas, axis=0)
    assert len(betas) == timesteps, f"Length of betas ({len(betas)}) does not match timesteps ({timesteps}) for schedule {schedule}"
    return betas, alphas, alpha_bars


def q_sample(
    x0: np.ndarray,
    t: int,
    sqrt_alpha_bars: np.ndarray,
    sqrt_one_minus_alpha_bars: np.ndarray,
) -> np.ndarray:
    noise = np.random.randn(*x0.shape)
    return sqrt_alpha_bars[t] * x0 + sqrt_one_minus_alpha_bars[t] * noise


def visualise_forward_process():
    target_path = CONFIG["preprocessing"]["targets_output"]
    targets = xr.open_dataset(target_path)
    x0 = targets.isel(time=0).sel(channel="tas")[VALUE_KEY].values

    # timesteps to display: always include t=0 and t=T-1
    ts = np.linspace(0, TIMESTEPS - 1, N_SHOWN, dtype=int, endpoint=True)

    n_rows = len(SCHEDULES)
    n_cols = N_SHOWN
    fig, axes = plt.subplots(
        n_rows, n_cols,
        figsize=(n_cols * 2.5, n_rows * 2.5),
        layout="constrained",
    )

    # share colour limits per row so noise growth is visually comparable
    vmin, vmax = x0.min(), x0.max()

    for row, schedule in enumerate(SCHEDULES):
        betas, alphas, alpha_bars = noise_schedule(
            schedule, TIMESTEPS, BETA_START, BETA_END
        )
        sqrt_alpha_bars = np.sqrt(alpha_bars)
        sqrt_one_minus_alpha_bars = np.sqrt(1.0 - alpha_bars)

        # fix a single noise draw per schedule so spatial structure is comparable
        np.random.seed(0)

        for col, t in enumerate(ts):
            ax = axes[row, col]

            if t == 0:
                img = x0
            else:
                img = q_sample(x0, t, sqrt_alpha_bars, sqrt_one_minus_alpha_bars)

            ax.imshow(img, origin="lower", cmap="coolwarm", vmin=vmin, vmax=vmax)
            ax.axis("off")

            if col == 0:
                ax.set_title(f"t = {t}", fontsize=8)
                ax.set_ylabel(schedule, fontsize=9)
                # ylabel won't show with axis("off"), use text instead
                ax.text(
                    -0.08, 0.5, schedule,
                    transform=ax.transAxes,
                    fontsize=9, fontweight="bold",
                    va="center", ha="right", rotation=90,
                )
            else:
                ax.set_title(f"t = {t}", fontsize=8)

    fig.suptitle("Forward diffusion process — single sample", fontsize=12)
    return fig


if __name__ == "__main__":
    fig = visualise_forward_process()
