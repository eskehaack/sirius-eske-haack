def run_reconstruction_test(
    run_id: str,
    checkpoint: str = "last",
    num_steps: int = 100,
    scenario: str = "historical",
    member: str = "r1i1p1f1",
    date: str = "1951-01-01",
    config_path: str = "./src/configs/sample_config.toml",
    traj_var_idx: int = 0,
):
    """
    DDIM reconstruction test on a single sample.

    Steps
    -----
    1.  Load the model and one real sample.
    2.  Forward (inversion): encode x0 → xT with deterministic DDIM inversion.
    3.  Reverse (decoding):  decode xT → x0_rec with deterministic DDIM (η=0).
    4.  Compute per-variable reconstruction metrics.
    5.  Save three diagnostic figures.
    6.  Run noise-level error sweep to expose where the model is weak.

    A well-trained model should recover x0 with low RMSE — a high reconstruction
    error indicates either model capacity issues or a training problem.
    """
    out_dir = Path(f"./samples/{run_id}/reconstruction_{scenario}_{member}_{date.replace('-', '')}")
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"\n{'='*60}")
    print(f"  DDIM Reconstruction Test")
    print(f"  run_id   : {run_id}")
    print(f"  date     : {date}  scenario: {scenario}  member: {member}")
    print(f"  steps    : {num_steps}")
    print(f"{'='*60}\n")

    # ------------------------------------------------------------------
    # 1. Load model and data
    # ------------------------------------------------------------------
    model = load_checkpoint(run_id, checkpoint)
    config = toml.load(config_path)
    data = load_sample(config, date=date, scenario=scenario, member=member)
    stats = xr.open_dataset(config["preprocessing"]["normalization_stats_path"])

    def ds_to_channels(ds):
        channels = []
        for v in ds.data_vars:
            arr = ds[v].values
            channels.append(arr[np.newaxis] if arr.ndim == 2 else arr)
        return np.concatenate(channels, axis=0)

    static_zarr = xr.open_dataset(config["preprocessing"]["static_output"])
    static = torch.from_numpy(ds_to_channels(static_zarr)).unsqueeze(0).float().to(model.device)

    x = torch.from_numpy(ds_to_channels(data["predictors"])).unsqueeze(0).float().to(model.device)
    x_norm = normalize(x.clone(), stats)

    target_shape = data["targets"]["lon"].shape  # (H, W) of the HR target grid
    condition, (pad_x, pad_y) = get_resized(model.image_size, target_shape, x_norm, static)
    condition = condition.to(model.device)
    condition[condition != condition] = 0.0  # Replace NaNs

    # Build the normalised x0 (target) in model space — same padding as condition
    target_vars = TARGET_VARS
    x0_channels = []
    for var in target_vars:
        arr = data["targets"][var].values  # (H, W)
        # residualise: subtract regridded predictor
        arr = arr - data["regridded"][var].values
        # normalise
        mean = stats[var].sel(statistic="targ_mean").values
        std  = stats[var].sel(statistic="targ_std").values
        arr = (arr - mean) / std
        x0_channels.append(torch.from_numpy(arr.astype(np.float32)))

    x0 = torch.stack(x0_channels, dim=0).unsqueeze(0).to(model.device)  # (1, 4, H, W)
    x0 = F.pad(
        x0,
        pad=(pad_y, pad_y, pad_x, pad_x),
        mode="constant",
        value=0.0,
    )

    print(f"  x0 shape     : {x0.shape}")
    print(f"  condition shape : {condition.shape}")

    # ------------------------------------------------------------------
    # 2. Forward pass: encode x0 → xT
    # ------------------------------------------------------------------
    print("\n[1/3] Running DDIM inversion (x0 → xT) …")
    xT, forward_traj = ddim_inversion(model, x0, condition, num_steps=num_steps)

    xT_noise = xT.std().item()
    print(f"  xT std  (should be ≈ 1.0 for a good inversion): {xT_noise:.4f}")

    # ------------------------------------------------------------------
    # 3. Reverse pass: decode xT → x0_rec
    # ------------------------------------------------------------------
    print("\n[2/3] Running DDIM decoding (xT → x0_rec) …")
    x0_rec, reverse_traj = ddim_decode(model, xT, condition, num_steps=num_steps)

    # ------------------------------------------------------------------
    # 4. Metrics
    # ------------------------------------------------------------------
    print("\n[3/3] Computing reconstruction metrics …")
    with torch.no_grad():
        x0_phys = unnormalize(x0.clone(), stats, target_vars)
        x0_rec_phys = unnormalize(x0_rec.clone(), stats, target_vars)
        x0_phys   = _crop(x0_phys,   pad_x, pad_y).cpu()
        x0_rec_phys = _crop(x0_rec_phys, pad_x, pad_y).cpu()

    print(f"\n  {'Variable':<10} {'RMSE':>8} {'MAE':>8} {'Bias':>8}")
    print(f"  {'-'*38}")
    for i, var in enumerate(target_vars):
        orig = x0_phys[0, i].numpy()
        rec  = x0_rec_phys[0, i].numpy()
        rmse = float(np.sqrt(np.mean((orig - rec) ** 2)))
        mae  = float(np.mean(np.abs(orig - rec)))
        bias = float(np.mean(rec - orig))
        print(f"  {var:<10} {rmse:>8.4f} {mae:>8.4f} {bias:>+8.4f}")

    # ------------------------------------------------------------------
    # 5. Figures
    # ------------------------------------------------------------------
    print("\nSaving diagnostic figures …")

    # Figure 1 — trajectory for chosen variable
    plot_trajectory(
        forward_traj, reverse_traj,
        var_idx=traj_var_idx,
        output_path=out_dir / f"trajectory_{TARGET_VARS[traj_var_idx]}.png",
    )

    # Figure 2 — reconstruction summary (all variables)
    plot_reconstruction_summary(
        x0, x0_rec, pad_x, pad_y, stats, data,
        output_path=out_dir / "reconstruction_summary.png",
    )

    # Figure 3 — noise-level error sweep
    plot_noise_level_error(
        model, x0, condition,
        output_path=out_dir / "noise_level_error.png",
    )

    print(f"\nAll outputs saved to: {out_dir}\n")


