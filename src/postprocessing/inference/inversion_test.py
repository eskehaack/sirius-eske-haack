@torch.no_grad()
def ddim_inversion(
    model,
    x0: torch.Tensor,
    condition: torch.Tensor,
    num_steps: int = 100,
) -> tuple[torch.Tensor, list[torch.Tensor]]:
    """
    Deterministically encode x0 into xT using the forward DDIM ODE.

    At each step we invert the DDIM update:
        x_{tau+1} = sqrt(ab_{t+1}) * x0_pred + sqrt(1 - ab_{t+1}) * eps_pred

    Args:
        model:      LitConditionalDDPM (with alpha_bars registered buffer).
        x0:         Clean sample  [B, C, H, W].
        condition:  Conditioning  [B, Cc, H, W].
        num_steps:  Number of inversion steps (more = more accurate).

    Returns:
        xT:         The encoded noise tensor  [B, C, H, W].
        trajectory: List of intermediate tensors (evenly spaced snapshots).
    """
    model.eval()
    device = x0.device
    b = x0.shape[0]
    T = model.hparams.timesteps

    # Build a forward timestep sequence: 0 → T-1 (inversion direction)
    tau = torch.linspace(0, T - 1, num_steps, device=device).long()
    alpha_bars = model.alpha_bars

    x = x0.clone()
    trajectory = [x.cpu()]

    snapshot_interval = max(1, num_steps // 10)  # Keep ~10 snapshots

    for i in range(num_steps - 1):
        t_curr = tau[i].item()
        t_next = tau[i + 1].item()

        ab_curr = alpha_bars[t_curr]
        ab_next = alpha_bars[t_next]

        t_batch = torch.full((b,), t_curr, device=device, dtype=torch.long)
        eps_pred = model.model(x, condition, t_batch)

        # Estimate x0 from the current noisy x
        x0_pred = (x - (1 - ab_curr).sqrt() * eps_pred) / ab_curr.sqrt()

        # Move to the next (more noisy) step along the ODE
        x = ab_next.sqrt() * x0_pred + (1 - ab_next).sqrt() * eps_pred

        if (i + 1) % snapshot_interval == 0:
            trajectory.append(x.cpu())

    trajectory.append(x.cpu())  # xT
    return x, trajectory


@torch.no_grad()
def ddim_decode(
    model,
    xT: torch.Tensor,
    condition: torch.Tensor,
    num_steps: int = 100,
) -> tuple[torch.Tensor, list[torch.Tensor]]:
    """
    Decode xT → x0 using deterministic DDIM (eta=0).

    Returns:
        x0_rec:     Reconstructed clean sample  [B, C, H, W].
        trajectory: List of intermediate tensors (evenly spaced snapshots).
    """
    x0_rec = model.sample_ddim(condition, num_steps=num_steps, eta=0.0, shape=xT.shape)

    # Re-run to capture trajectory (sample_ddim doesn't expose it, so we redo)
    model.eval()
    device = condition.device
    b = xT.shape[0]
    T = model.hparams.timesteps

    tau = torch.linspace(T - 1, 0, num_steps, device=device).long()
    alpha_bars = model.alpha_bars
    alpha_bar_tau = alpha_bars[tau]
    alpha_bar_tau_prev = torch.cat(
        [alpha_bars[tau[1:]], torch.ones(1, device=device, dtype=alpha_bars.dtype)],
        dim=0,
    )

    x = xT.clone()
    trajectory = [x.cpu()]
    snapshot_interval = max(1, num_steps // 10)

    for i in range(num_steps):
        t_idx = tau[i].item()
        ab_t = alpha_bar_tau[i]
        ab_prev = alpha_bar_tau_prev[i]

        t_batch = torch.full((b,), t_idx, device=device, dtype=torch.long)
        eps = model.model(x, condition, t_batch)
        x0_pred = (x - (1 - ab_t).sqrt() * eps) / ab_t.sqrt()
        dir_xt = (1 - ab_prev).clamp(min=0.0).sqrt() * eps

        if t_idx > 0:
            x = ab_prev.sqrt() * x0_pred + dir_xt
        else:
            x = x0_pred

        if (i + 1) % snapshot_interval == 0:
            trajectory.append(x.cpu())

    trajectory.append(x.cpu())
    return x, trajectory


