TARGET_VARS = ["tas", "tasmin", "tasmax", "pr"]

def _crop(tensor: torch.Tensor, pad_x: int, pad_y: int) -> torch.Tensor:
    """Remove zero-padding added for model requirements."""
    h, w = tensor.shape[-2], tensor.shape[-1]
    return tensor[
        ...,
        pad_x: h - pad_x if pad_x > 0 else None,
        pad_y: w - pad_y if pad_y > 0 else None,
    ]


def plot_trajectory(
    forward_traj: list[torch.Tensor],
    reverse_traj: list[torch.Tensor],
    var_idx: int,
    output_path: Path,
):
    """
    Plot the noising (forward) and denoising (reverse) trajectory
    for a single variable channel side-by-side.
    """
    n_fwd = len(forward_traj)
    n_rev = len(reverse_traj)
    total = n_fwd + n_rev
    fig, axes = plt.subplots(2, max(n_fwd, n_rev), figsize=(3 * max(n_fwd, n_rev), 7))
    fig.suptitle(f"Reconstruction trajectory — {TARGET_VARS[var_idx]}", fontsize=14)

    vmin = forward_traj[0][0, var_idx].min().item()
    vmax = forward_traj[0][0, var_idx].max().item()

    for j, frame in enumerate(forward_traj):
        ax = axes[0, j]
        ax.imshow(frame[0, var_idx].numpy(), vmin=vmin, vmax=vmax, cmap="RdBu_r", origin="lower")
        frac = j / max(n_fwd - 1, 1)
        ax.set_title(f"t≈{int(frac * 100)}%T", fontsize=8)
        ax.axis("off")
    for j in range(n_fwd, max(n_fwd, n_rev)):
        axes[0, j].axis("off")
    axes[0, 0].set_ylabel("Forward (noising)", fontsize=9)

    for j, frame in enumerate(reverse_traj):
        ax = axes[1, j]
        ax.imshow(frame[0, var_idx].numpy(), vmin=vmin, vmax=vmax, cmap="RdBu_r", origin="lower")
        frac = 1.0 - j / max(n_rev - 1, 1)
        ax.set_title(f"t≈{int(frac * 100)}%T", fontsize=8)
        ax.axis("off")
    for j in range(n_rev, max(n_fwd, n_rev)):
        axes[1, j].axis("off")
    axes[1, 0].set_ylabel("Reverse (denoising)", fontsize=9)

    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved trajectory plot → {output_path}")


def plot_reconstruction_summary(
    x0: torch.Tensor,
    x0_rec: torch.Tensor,
    pad_x: int,
    pad_y: int,
    stats: xr.Dataset,
    data: dict,
    output_path: Path,
):
    """
    4-panel figure per variable:
      [Original | Reconstruction | Absolute error | Error histogram]
    """
    # Unnormalize both tensors so they are in physical units
    x0_phys = unnormalize(x0.clone(), stats, TARGET_VARS)
    x0_rec_phys = unnormalize(x0_rec.clone(), stats, TARGET_VARS)

    x0_phys = _crop(x0_phys, pad_x, pad_y).cpu()
    x0_rec_phys = _crop(x0_rec_phys, pad_x, pad_y).cpu()

    n_vars = len(TARGET_VARS)
    fig = plt.figure(figsize=(16, 4 * n_vars))
    gs = gridspec.GridSpec(n_vars, 4, figure=fig, hspace=0.4, wspace=0.3)
    fig.suptitle("DDIM Reconstruction Quality", fontsize=16, y=1.01)

    for i, var in enumerate(TARGET_VARS):
        orig = x0_phys[0, i].numpy()
        rec  = x0_rec_phys[0, i].numpy()
        err  = np.abs(orig - rec)

        rmse = float(np.sqrt(np.mean((orig - rec) ** 2)))
        mae  = float(np.mean(err))
        bias = float(np.mean(rec - orig))

        shared_vmin = min(orig.min(), rec.min())
        shared_vmax = max(orig.max(), rec.max())

        # Original
        ax0 = fig.add_subplot(gs[i, 0])
        im = ax0.imshow(orig, vmin=shared_vmin, vmax=shared_vmax, cmap="RdBu_r", origin="lower")
        ax0.set_title(f"{var} — Original")
        ax0.axis("off")
        plt.colorbar(im, ax=ax0, shrink=0.8)

        # Reconstruction
        ax1 = fig.add_subplot(gs[i, 1])
        im = ax1.imshow(rec, vmin=shared_vmin, vmax=shared_vmax, cmap="RdBu_r", origin="lower")
        ax1.set_title(f"{var} — Reconstructed")
        ax1.axis("off")
        plt.colorbar(im, ax=ax1, shrink=0.8)

        # Absolute error map
        ax2 = fig.add_subplot(gs[i, 2])
        im = ax2.imshow(err, cmap="hot_r", origin="lower")
        ax2.set_title(f"|Error|  RMSE={rmse:.3f}  bias={bias:.3f}")
        ax2.axis("off")
        plt.colorbar(im, ax=ax2, shrink=0.8)

        # Error histogram
        ax3 = fig.add_subplot(gs[i, 3])
        flat_err = (rec - orig).ravel()
        ax3.hist(flat_err, bins=60, color="steelblue", edgecolor="none", alpha=0.8)
        ax3.axvline(0, color="k", lw=1.5, ls="--")
        ax3.set_title(f"Error distribution  MAE={mae:.3f}")
        ax3.set_xlabel("rec − orig")
        ax3.set_ylabel("count")

    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved reconstruction summary → {output_path}")


def plot_noise_level_error(
    model,
    x0: torch.Tensor,
    condition: torch.Tensor,
    output_path: Path,
    n_levels: int = 20,
):
    """
    At multiple noise levels t, compute the single-step noise prediction error.
    Plots MSE vs. t to reveal at which part of the diffusion trajectory the
    model struggles most.
    """
    model.eval()
    device = x0.device
    T = model.hparams.timesteps

    t_values = torch.linspace(0, T - 1, n_levels, device=device).long()
    mse_per_t = []

    with torch.no_grad():
        for t_val in t_values:
            t_batch = t_val.unsqueeze(0)
            noise = torch.randn_like(x0)
            x_t = model.q_sample(x0, t_batch, noise)
            eps_pred = model.model(x_t, condition, t_batch)
            mse = F.mse_loss(eps_pred, noise).item()
            mse_per_t.append(mse)

    t_axis = t_values.cpu().numpy()

    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(t_axis, mse_per_t, marker="o", color="steelblue", linewidth=1.5)

    plt.annotate(f"{mse_per_t[0]:.4E}", (t_axis[0], mse_per_t[0]-0.01), textcoords='data')
    plt.annotate(f"{mse_per_t[-1]:.4E}", (t_axis[-1], mse_per_t[-1]+0.01), textcoords='data')

    ax.set_xlabel("Timestep t")
    ax.set_ylabel("Noise prediction MSE")
    ax.set_title("Noise prediction error vs. diffusion timestep")
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved noise-level error plot → {output_path}")


