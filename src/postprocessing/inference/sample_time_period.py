# Running period statistics
# ----------------------------------------------------

class PeriodAccumulator:
    """Per-pixel running sums over days, NaN-aware. Inputs are (B, C, H, W)."""

    def __init__(self):
        self.sum_pred = self.sum_truth = self.sum_sqerr = self.count = None
        self.n_days = 0

    def update(self, pred: torch.Tensor, truth: torch.Tensor):
        pred, truth = pred.double(), truth.double()
        valid = ~(torch.isnan(truth) | torch.isnan(pred))
        p = torch.where(valid, pred, torch.zeros_like(pred))
        t = torch.where(valid, truth, torch.zeros_like(truth))

        if self.sum_pred is None:
            self.sum_pred = torch.zeros_like(p[0])
            self.sum_truth = torch.zeros_like(p[0])
            self.sum_sqerr = torch.zeros_like(p[0])
            self.count = torch.zeros_like(p[0])

        self.sum_pred += p.sum(0)
        self.sum_truth += t.sum(0)
        self.sum_sqerr += ((p - t) ** 2).sum(0)
        self.count += valid.double().sum(0)
        self.n_days += pred.shape[0]

    def result(self) -> dict[str, torch.Tensor]:
        n = self.count.clamp(min=1)
        empty = self.count == 0
        nan = torch.full_like(n, float("nan"))
        return {
            "mean_pred": torch.where(empty, nan, self.sum_pred / n),
            "mean_truth": torch.where(empty, nan, self.sum_truth / n),
            "rms_daily_error": torch.where(empty, nan, (self.sum_sqerr / n).sqrt()),
        }


def period_metrics(res: dict, daily: pd.DataFrame, target_vars: list[str]) -> dict:
    out = {}
    for i, var in enumerate(target_vars):
        mp = res["mean_pred"][i]
        mt = res["mean_truth"][i]
        diff = mp - mt
        ok = ~torch.isnan(diff)
        if ok.sum() > 1:
            corr = float(np.corrcoef(mp[ok].numpy(), mt[ok].numpy())[0, 1])
        else:
            corr = float("nan")
        out[var] = {
            "bias_of_period_mean": float(torch.nanmean(diff)),
            "rmse_of_period_mean": float(torch.nanmean(diff ** 2).sqrt()),
            "pattern_corr_of_period_mean": corr,
            "mean_daily_rmse": float(daily.loc[daily["var"] == var, "daily_rmse"].mean()),
        }
    return out


def daily_records(dates, pred, truth, target_vars, space) -> list[dict]:
    """One row per (day, variable) with domain means and that day's RMSE."""
    rows = []
    for b, date in enumerate(dates):
        for i, var in enumerate(target_vars):
            p, t = pred[b, i], truth[b, i]
            rows.append({
                "date": date,
                "space": space,
                "var": var,
                "pred_domain_mean": float(torch.nanmean(p)),
                "truth_domain_mean": float(torch.nanmean(t)),
                "daily_rmse": float(torch.nanmean((p - t) ** 2).sqrt()),
            })
    return rows


def print_metrics(metrics: dict, label: str):
    print(f"\n{label}")
    print(f"{'var':<16}{'bias':>11}{'rmse(mean)':>12}{'corr(mean)':>12}{'daily rmse':>12}")
    for var, m in metrics.items():
        print(f"{var:<16}{m['bias_of_period_mean']:>11.4f}{m['rmse_of_period_mean']:>12.4f}"
              f"{m['pattern_corr_of_period_mean']:>12.3f}{m['mean_daily_rmse']:>12.4f}")


