def plot_period_maps(res: dict, target_vars: list[str], path: Path, title: str):
    n = len(target_vars)
    fig, axes = plt.subplots(n, 4, figsize=(18, 4 * n), squeeze=False)
    for i, var in enumerate(target_vars):
        mt = res["mean_truth"][i].numpy()
        mp = res["mean_pred"][i].numpy()
        diff = mp - mt
        vmin, vmax = np.nanpercentile(mt, [1, 99])
        elim = np.nanpercentile(np.abs(diff), 99)
        panels = [
            (mt, "period mean truth", dict(vmin=vmin, vmax=vmax, cmap="viridis")),
            (mp, "period mean prediction", dict(vmin=vmin, vmax=vmax, cmap="viridis")),
            (diff, "prediction − truth", dict(vmin=-elim, vmax=elim, cmap="RdBu_r")),
            (res["rms_daily_error"][i].numpy(), "RMS daily error", dict(cmap="magma")),
        ]
        for ax, (field, name, kw) in zip(axes[i], panels):
            im = ax.imshow(field, origin="lower", **kw)
            ax.set_title(f"{var}: {name}")
            ax.set_xticks([])
            ax.set_yticks([])
            fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def plot_timeseries(daily: pd.DataFrame, target_vars: list[str], path: Path, title: str):
    n = len(target_vars)
    fig, axes = plt.subplots(n, 1, figsize=(12, 3 * n), squeeze=False, sharex=True)
    for ax, var in zip(axes[:, 0], target_vars):
        d = daily[daily["var"] == var].groupby("date", as_index=False).mean(numeric_only=True)
        ax.plot(d["date"], d["truth_domain_mean"], label="truth", color="black")
        ax.plot(d["date"], d["pred_domain_mean"], label="prediction", color="tab:orange")
        ax.set_ylabel(var)
        ax.legend(loc="upper right")
    axes[-1, 0].set_xlabel("date")
    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


