def dataset_times(dataset) -> pd.DatetimeIndex:
    """Timestamp for every dataset position, using the same time axis build_indices used."""
    return pd.to_datetime(dataset.predictors.time.values[dataset.indices])


def find_period_positions(dataset, periods: list[tuple[str, str]]) -> np.ndarray:
    """Dataset positions whose date falls in any [start, end] block (inclusive, whole days)."""
    days = dataset_times(dataset).normalize()
    mask = np.zeros(len(days), dtype=bool)
    for start, end in periods:
        mask |= (days >= pd.Timestamp(start).normalize()) & (days <= pd.Timestamp(end).normalize())
    return np.flatnonzero(mask)


