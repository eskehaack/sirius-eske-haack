def main(
    run_id: str,
    periods: list[tuple[str, str]],
    label: str | None = None,
    checkpoint: str = "last",
    config_path: str = "./src/configs/training_config.toml",
    split: str = "auto",
    batch_size: int = 1,
    num_workers: int | None = None,
    first_occurrence_only: bool = False,
    timesteps: int = 500,
    sample_type: str = "ddpm",
    cfg_scale: float = 1.0,
    eta: float = 0.0,
    seed: int = 42,
    amp: bool = False,
    stats_path: str | None = None,
):
    pl.seed_everything(seed, workers=True)
    torch.set_float32_matmul_precision("medium")
    os.makedirs("dist_test", exist_ok=True)  # sample_ddpm writes step diagnostics here

    if num_workers is None:
        num_workers = int(parse_config("training", config_path)["num_workers"])

    # Build the datasets exactly as trainer.fit() would
    datamodule = DataModule(batch_size=batch_size, num_workers=num_workers, config_path=config_path)
    datamodule.prepare_data()
    datamodule.setup(stage="fit")
    datasets = {"val": datamodule.val_ds, "train": datamodule.train_ds}
    search = ["val", "train"] if split == "auto" else [split]

    # ---- find which dataset positions / batches the period covers
    selection = {}
    for name in search:
        ds = datasets[name]
        positions = find_period_positions(ds, periods)
        if len(positions) == 0:
            continue
        times = dataset_times(ds)
        days = times[positions].normalize()
        duplicated = days.duplicated()
        if duplicated.any():
            print(f"[{name}] {duplicated.sum()} dates occur more than once "
                  f"(several scenarios/members concatenated along time).")
            if first_occurrence_only:
                positions = positions[~duplicated]
                print(f"[{name}] keeping first occurrence only -> {len(positions)} samples")
        selection[name] = positions

        batch_ids = np.unique(positions // batch_size)
        print(f"[{name}] {len(positions)} samples, {times[positions].min():%Y-%m-%d} to {times[positions].max():%Y-%m-%d}")
        print(f"[{name}] dataset positions {positions.min()}–{positions.max()}, "
              f"corresponding {name}_dataloader batch indices (batch_size={batch_size}, unshuffled): "
              f"{batch_ids.min()}–{batch_ids.max()}")
        if name == "train":
            print("[train] Warning: these dates are in the training split, so this is an in-sample evaluation.")

    if not selection:
        raise ValueError(f"No samples found for periods {periods} in split(s) {search}.")

    model, config = load_checkpoint(run_id, checkpoint)
    device = model.device
    stats = load_stats(config_path, stats_path)

    use_amp = amp and device.type == "cuda"
    autocast = (
        torch.autocast(device_type="cuda", dtype=torch.float16)
        if use_amp else contextlib.nullcontext()
    )

    acc_norm, acc_phys = PeriodAccumulator(), PeriodAccumulator()
    rows = []
    target_vars = None
    sample_hparams = {"cfg_scale": cfg_scale, "eta": eta}

    for name, positions in selection.items():
        ds = datasets[name]
        times = dataset_times(ds)
        # Same Dataset, __getitem__ and default collate as training; only the index set is restricted
        loader = DataLoader(
            Subset(ds, positions.tolist()),
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=True,
        )

        for step, batch in enumerate(loader):
            batch = move_batch_like_trainer(batch, model, datamodule, device)
            if target_vars is None:
                target_vars = list(batch[1].keys())
            dates = [times[int(i)].normalize() for i in batch[3].cpu()]  # batch[3] = dataset position

            with torch.no_grad(), autocast:
                x0, condition = model._load_batch(batch)
                # One member per day: each batch item is a different day
                pred = model.sample(condition, num_steps=timesteps, hparams=sample_hparams)

            pred = model._crop(pred).float().cpu()
            truth = model._crop(x0).float().cpu()

            acc_norm.update(pred, truth)
            rows += daily_records(dates, pred, truth, target_vars, "normalized")

            if stats is not None:
                pred_p = unnormalize(pred, stats, target_vars)
                truth_p = unnormalize(truth, stats, target_vars)
                acc_phys.update(pred_p, truth_p)
                rows += daily_records(dates, pred_p, truth_p, target_vars, "physical")

            print(f"[{name}] batch {step + 1}/{len(loader)} done "
                  f"({dates[0]:%Y-%m-%d}{'' if len(dates) == 1 else f' … {dates[-1]:%Y-%m-%d}'})")

    # ---- results
    if label is None:
        label = "_".join(f"{pd.Timestamp(s):%Y%m%d}-{pd.Timestamp(e):%Y%m%d}" for s, e in periods)
    out_dir = Path(f"./samples/{run_id}/period_{label}")
    out_dir.mkdir(parents=True, exist_ok=True)
    tag = f"{sample_type}_{timesteps}_cfg{cfg_scale:g}"

    daily = pd.DataFrame(rows)
    daily.to_csv(out_dir / f"daily_{tag}.csv", index=False)

    summary = {
        "periods": [list(p) for p in periods],
        "n_days": acc_norm.n_days,
        "splits": {k: int(len(v)) for k, v in selection.items()},
        "target_vars": target_vars,
    }
    spaces = [("normalized", acc_norm)] + ([("physical", acc_phys)] if stats is not None else [])
    for space, acc in spaces:
        res = acc.result()
        metrics = period_metrics(res, daily[daily["space"] == space], target_vars)
        summary[space] = metrics
        print_metrics(metrics, f"{label} | {acc.n_days} days | {space}")

        for key, arr in res.items():
            np.save(out_dir / f"{key}_{space}_{tag}.npy", arr.float().numpy())
        plot_period_maps(res, target_vars, out_dir / f"period_maps_{space}_{tag}.png",
                         title=f"{run_id} | {label} | {acc.n_days} days | {space}")
        plot_timeseries(daily[daily["space"] == space], target_vars,
                        out_dir / f"timeseries_{space}_{tag}.png",
                        title=f"{run_id} | {label} | domain mean | {space}")

    with open(out_dir / f"metrics_{tag}.yaml", "w") as f:
        yaml.safe_dump(summary, f, sort_keys=False)
    print(f"\nSaved results to {out_dir.resolve()}")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Sample one member per day over a date period and evaluate the period-average prediction."
    )
    parser.add_argument("--run_id", type=str, required=True, help="Run ID defining directory for checkpoint file")
    parser.add_argument("--period", nargs=2, action="append", required=True, metavar=("START", "END"),
                        help="Inclusive date block, e.g. --period 1956-01-01 1956-03-31. Repeat to add blocks.")
    parser.add_argument("--label", type=str, default=None, help="Name for the output folder, e.g. winter1956")
    parser.add_argument("--checkpoint", type=str, default="last", help="Name of checkpoint file")
    parser.add_argument("--config_path", type=str, default="./src/configs/training_config.toml",
                        help="Training config used to build the DataModule")
    parser.add_argument("--split", type=str, default="auto", choices=["auto", "val", "train"],
                        help="Where to look for the dates; 'auto' searches val and train")
    parser.add_argument("--batch_size", type=int, default=1, help="Days sampled in parallel")
    parser.add_argument("--num_workers", type=int, default=None,
                        help="Dataloader workers (defaults to the training config value)")
    parser.add_argument("--first_occurrence_only", action="store_true",
                        help="If a date appears for several realizations, keep only the first one")
    parser.add_argument("--timesteps", type=int, default=500, help="Number of reverse diffusion steps")
    parser.add_argument("--sample_type", type=str, default="ddpm", choices=["ddpm", "ddim"])
    parser.add_argument("--cfg_scale", type=float, default=1.0, help="Classifier-free guidance scale for DDPM")
    parser.add_argument("--eta", type=float, default=0.0, help="DDIM stochasticity (0 = deterministic)")
    parser.add_argument("--seed", type=int, default=42, help="Seed passed to pl.seed_everything")
    parser.add_argument("--amp", action="store_true", help="fp16 autocast, like precision='16-mixed' in training")
    parser.add_argument("--stats_path", type=str, default=None,
                        help="Normalization stats file; defaults to [preprocessing].normalization_stats_path")
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
